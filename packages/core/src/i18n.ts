const MESSAGES: Record<Locale, Record<MessageKey, string>> = { zh, en };

let current: Locale = 'zh';

/** Chinese for any `zh` variant, English otherwise. */
export function detectLocale(languages: readonly string[]): Locale {
  return languages[0]?.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function setLocale(locale: Locale): void {
  current = locale;
}

/** The message for `key` in the current locale, with `{name}` placeholders filled in. */
export function t(key: MessageKey, vars: Record<string, string | number> = {}): string {
  return MESSAGES[current][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
